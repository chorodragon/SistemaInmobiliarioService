    Oferta_idOferta NUMBER(10) NOT NULL,
    CONSTRAINT fk_contrato_oferta FOREIGN KEY (Oferta_idOferta)
        REFERENCES Oferta (idOferta)
);

CREATE INDEX ix_contrato_oferta ON Contrato (Oferta_idOferta);

ALTER TABLE Oferta ADD (fecha DATE);

ALTER TABLE ContraOferta ADD (fecha DATE);

ALTER TABLE ContraOferta ADD (
    estado              VARCHAR2(45),
    origen              VARCHAR2(45) NOT NULL,  
    TipoPago_idTipoPago NUMBER(10) NOT NULL,
    CONSTRAINT fk_contraoferta_tipopago FOREIGN KEY (TipoPago_idTipoPago)
        REFERENCES TipoPago (idTipoPago)
);

CREATE INDEX ix_contraoferta_tipopago ON ContraOferta (TipoPago_idTipoPago);

ALTER TABLE Usuario ADD (
    email    VARCHAR2(100),
    usuario  VARCHAR2(45)  NOT NULL,
    pass     VARCHAR2(100) NOT NULL,
    CONSTRAINT uq_usuario_usuario UNIQUE (usuario)
);

ALTER TABLE Agente ADD (
    email    VARCHAR2(100),
    usuario  VARCHAR2(45)  NOT NULL,
    pass     VARCHAR2(100) NOT NULL,
    CONSTRAINT uq_agente_usuario UNIQUE (usuario)
);

CREATE SEQUENCE seq_agente_codigo START WITH 1 INCREMENT BY 1 NOCACHE;

ALTER TABLE Agente MODIFY (codigo DEFAULT ON NULL seq_agente_codigo.NEXTVAL);

ALTER TABLE Agente ADD CONSTRAINT uq_agente_codigo UNIQUE (codigo);

ALTER TABLE Prestamos MODIFY (monto NUMBER(14,2));

CREATE TABLE Notificaciones (
    idNotificacion      NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    mensaje             VARCHAR2(255),
    fecha               DATE,
    leida               NUMBER(1),
    Usuario_idUsuario   NUMBER(10) NOT NULL,
    Agente_idAgente     NUMBER(10) NOT NULL,
    CONSTRAINT pk_notificaciones PRIMARY KEY (idNotificacion),
    CONSTRAINT fk_notificaciones_usuario FOREIGN KEY (Usuario_idUsuario)
        REFERENCES Usuario (idUsuario),
    CONSTRAINT fk_notificaciones_agente FOREIGN KEY (Agente_idAgente)
        REFERENCES Agente (idAgente)
);

CREATE INDEX ix_notificaciones_usuario ON Notificaciones (Usuario_idUsuario);
CREATE INDEX ix_notificaciones_agente  ON Notificaciones (Agente_idAgente);

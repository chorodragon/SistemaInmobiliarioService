CREATE USER inmobiliario IDENTIFIED BY "Inmobiliario123"
    DEFAULT TABLESPACE users
    TEMPORARY TABLESPACE temp
    QUOTA UNLIMITED ON users;

GRANT CREATE SESSION,
      CREATE TABLE,
      CREATE SEQUENCE,
      CREATE VIEW,
      CREATE PROCEDURE,
      CREATE TRIGGER
   TO inmobiliario;

ALTER SESSION SET CURRENT_SCHEMA = inmobiliario;


CREATE TABLE Usuario (
    idUsuario       NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    nombre          VARCHAR2(45),
    apellido        VARCHAR2(45),
    telefono        VARCHAR2(45),
    direccion       VARCHAR2(45),
    edad            NUMBER(10),
    nacionalidad    VARCHAR2(45),
    estadoCivil     VARCHAR2(45),
    CONSTRAINT pk_usuario PRIMARY KEY (idUsuario)
);

CREATE TABLE Agente (
    idAgente        NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    codigo          VARCHAR2(45) NOT NULL,
    nombre          VARCHAR2(45),
    apellido        VARCHAR2(45),
    CONSTRAINT pk_agente PRIMARY KEY (idAgente)
);

CREATE TABLE TipoInmueble (
    idTipoInmueble  NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    nombre          VARCHAR2(45),
    CONSTRAINT pk_tipoinmueble PRIMARY KEY (idTipoInmueble)
);

CREATE TABLE Caracteristicas (
    idCaracteristicas NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    caracteristica    VARCHAR2(45),
    CONSTRAINT pk_caracteristicas PRIMARY KEY (idCaracteristicas)
);

CREATE TABLE TipoPago (
    idTipoPago      NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    nombre          VARCHAR2(45),
    descripcion     VARCHAR2(45),
    CONSTRAINT pk_tipopago PRIMARY KEY (idTipoPago)
);


CREATE TABLE Comprador (
    idUsuario       NUMBER(10),
    CONSTRAINT pk_comprador PRIMARY KEY (idUsuario),
    CONSTRAINT fk_comprador_usuario FOREIGN KEY (idUsuario)
        REFERENCES Usuario (idUsuario)
);

CREATE TABLE Vendedor (
    idUsuario       NUMBER(10),
    antiguedad      NUMBER(10),
    cant_ventas     NUMBER(10),
    CONSTRAINT pk_vendedor PRIMARY KEY (idUsuario),
    CONSTRAINT fk_vendedor_usuario FOREIGN KEY (idUsuario)
        REFERENCES Usuario (idUsuario)
);


CREATE TABLE Inmueble (
    idInmueble                  NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    direccion                   VARCHAR2(45),
    precio                      NUMBER(14,2),
    metraje                     NUMBER(10,2),
    disponibilidad              NUMBER(10),
    Vendedor_idUsuario          NUMBER(10) NOT NULL,
    Agente_idAgente             NUMBER(10) NOT NULL,
    TipoInmueble_idTipoInmueble NUMBER(10) NOT NULL,
    CONSTRAINT pk_inmueble PRIMARY KEY (idInmueble),
    CONSTRAINT fk_inmueble_vendedor FOREIGN KEY (Vendedor_idUsuario)
        REFERENCES Vendedor (idUsuario),
    CONSTRAINT fk_inmueble_agente FOREIGN KEY (Agente_idAgente)
        REFERENCES Agente (idAgente),
    CONSTRAINT fk_inmueble_tipoinmueble FOREIGN KEY (TipoInmueble_idTipoInmueble)
        REFERENCES TipoInmueble (idTipoInmueble)
);

CREATE TABLE Detalle (
    IdDetalle                         NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    Caracteristicas_idCaracteristicas NUMBER(10) NOT NULL,
    Inmueble_idInmueble               NUMBER(10) NOT NULL,
    descripcion                       VARCHAR2(45),
    CONSTRAINT pk_detalle PRIMARY KEY (IdDetalle),
    CONSTRAINT fk_detalle_caracteristicas FOREIGN KEY (Caracteristicas_idCaracteristicas)
        REFERENCES Caracteristicas (idCaracteristicas),
    CONSTRAINT fk_detalle_inmueble FOREIGN KEY (Inmueble_idInmueble)
        REFERENCES Inmueble (idInmueble)
);


CREATE TABLE Oferta (
    idOferta              NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    monto                 NUMBER(14,2),
    tiempo                VARCHAR2(45),
    estado                VARCHAR2(45),
    Comprador_idUsuario   NUMBER(10) NOT NULL,
    Inmueble_idInmueble   NUMBER(10) NOT NULL,
    TipoPago_idTipoPago   NUMBER(10) NOT NULL,
    CONSTRAINT pk_oferta PRIMARY KEY (idOferta),
    CONSTRAINT fk_oferta_comprador FOREIGN KEY (Comprador_idUsuario)
        REFERENCES Comprador (idUsuario),
    CONSTRAINT fk_oferta_inmueble FOREIGN KEY (Inmueble_idInmueble)
        REFERENCES Inmueble (idInmueble),
    CONSTRAINT fk_oferta_tipopago FOREIGN KEY (TipoPago_idTipoPago)
        REFERENCES TipoPago (idTipoPago)
);

CREATE TABLE ContraOferta (
    idContraOferta   NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    monto            NUMBER(14,2),
    tiempo           VARCHAR2(45),
    prioridad        NUMBER(10),
    Oferta_idOferta  NUMBER(10) NOT NULL,
    CONSTRAINT pk_contraoferta PRIMARY KEY (idContraOferta),
    CONSTRAINT fk_contraoferta_oferta FOREIGN KEY (Oferta_idOferta)
        REFERENCES Oferta (idOferta)
);


CREATE TABLE Contrato (
    idContrato           NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    fecha                DATE,          
    monto                NUMBER(14,2),
    estado               NUMBER(10),
    TipoPago_idTipoPago  NUMBER(10) NOT NULL,
    CONSTRAINT pk_contrato PRIMARY KEY (idContrato),
    CONSTRAINT fk_contrato_tipopago FOREIGN KEY (TipoPago_idTipoPago)
        REFERENCES TipoPago (idTipoPago)
);

CREATE TABLE Prestamos (
    idPrestamos          NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    banco                VARCHAR2(45),
    monto                VARCHAR2(45), 
    plazo                VARCHAR2(45),
    intereses            NUMBER(7,4),
    estado               NUMBER(10),
    Contrato_idContrato  NUMBER(10) NOT NULL,
    CONSTRAINT pk_prestamos PRIMARY KEY (idPrestamos),
    CONSTRAINT fk_prestamos_contrato FOREIGN KEY (Contrato_idContrato)
        REFERENCES Contrato (idContrato)
);


CREATE INDEX ix_inmueble_vendedor     ON Inmueble (Vendedor_idUsuario);
CREATE INDEX ix_inmueble_agente       ON Inmueble (Agente_idAgente);
CREATE INDEX ix_inmueble_tipoinmueble ON Inmueble (TipoInmueble_idTipoInmueble);

CREATE INDEX ix_detalle_caract        ON Detalle (Caracteristicas_idCaracteristicas);
CREATE INDEX ix_detalle_inmueble      ON Detalle (Inmueble_idInmueble);

CREATE INDEX ix_oferta_comprador      ON Oferta (Comprador_idUsuario);
CREATE INDEX ix_oferta_inmueble       ON Oferta (Inmueble_idInmueble);
CREATE INDEX ix_oferta_tipopago       ON Oferta (TipoPago_idTipoPago);

CREATE INDEX ix_contraoferta_oferta   ON ContraOferta (Oferta_idOferta);
CREATE INDEX ix_contrato_tipopago     ON Contrato (TipoPago_idTipoPago);
CREATE INDEX ix_prestamos_contrato    ON Prestamos (Contrato_idContrato);

